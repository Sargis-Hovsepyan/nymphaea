// Lock a Groq API key with a password and write it into src/ai/sealed.ts: npm run seal-key
// Nothing typed here is echoed, written to shell history or sent anywhere.
import { writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { seal, unseal } from "../src/ai/vault";

const rl = createInterface({ input: process.stdin, output: process.stdout, terminal: !!process.stdin.isTTY });
// Hide what is typed: the prompt is written directly, the readline echo is dropped.
(rl as unknown as { _writeToOutput: (s: string) => void })._writeToOutput = () => {};
const lines = rl[Symbol.asyncIterator]();
const ask = async (q: string): Promise<string> => { process.stdout.write(q); const r = await lines.next(); process.stdout.write("\n"); return r.done ? "" : String(r.value).trim(); };

const key = await ask("Groq API key (gsk_…): ");
const pw = await ask("Owner password (12+ characters, a few random words is best): ");
const again = await ask("Same password again: ");
rl.close();
if (!/^gsk_\w{20,}$/.test(key)) throw new Error("That does not look like a Groq key.");
if (pw.length < 12) throw new Error("Too short: the locked key is public, so the password must be long.");
if (again !== pw) throw new Error("The passwords differ.");

const sealed = await seal(key, pw);
if ((await unseal(sealed, pw)) !== key) throw new Error("Self-check failed; nothing written.");
writeFileSync(new URL("../src/ai/sealed.ts", import.meta.url),
  "// Generated by `npm run seal-key`. The owner's Groq key, locked with their password (ai/vault.ts).\n" +
  "// Empty means no built-in key: the owner-password field stays hidden.\n" +
  `export const SEALED_GROQ = "${sealed}";\n`);
console.log("Locked into src/ai/sealed.ts. Now: npm run build, then commit and push.");
